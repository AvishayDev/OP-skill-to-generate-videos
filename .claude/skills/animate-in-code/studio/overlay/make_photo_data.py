#!/usr/bin/env python3
"""make_photo_data.py - embed a photo as a data URL so the canvas is never tainted.

Why: an <img src="file://..."> drawn on a canvas taints it, and toDataURL() (which render.mjs
uses to grab every frame) then throws. A data: URL is same-origin, so the canvas stays clean.

usage: python3 make_photo_data.py SRC.png|jpg [--max 1600] [--out photo-data.js] [--name PHOTO]
- Photos with transparency (cutouts) are kept as PNG, everything else becomes a resized JPG (q 88).
- Writes:  const PHOTO = { src: 'data:image/...;base64,...', w, h };
"""
import argparse, base64, io, sys
from PIL import Image

ap = argparse.ArgumentParser()
ap.add_argument('src'); ap.add_argument('--max', type=int, default=1600)
ap.add_argument('--out', default='photo-data.js'); ap.add_argument('--name', default='PHOTO')
a = ap.parse_args()
im = Image.open(a.src)
im.thumbnail((a.max, a.max), Image.LANCZOS)          # only ever shrinks
alpha = im.mode in ('RGBA', 'LA') and im.getchannel('A').getextrema()[0] < 255
buf = io.BytesIO()
if alpha: im.convert('RGBA').save(buf, 'PNG', optimize=True); mime = 'image/png'
else: im.convert('RGB').save(buf, 'JPEG', quality=88, optimize=True); mime = 'image/jpeg'
b64 = base64.b64encode(buf.getvalue()).decode()
with open(a.out, 'w') as f:
    f.write(f"'use strict';\n// generated by make_photo_data.py from {a.src.split('/')[-1]} - do not edit\n")
    f.write(f"const {a.name} = {{ src: 'data:{mime};base64,{b64}', w: {im.width}, h: {im.height} }};\n")
print(f'{a.out}: {mime} {im.width}x{im.height}, {len(b64)//1024} KB base64')
